"""
Supabase Client & Database Persistence Layer for Visionlytics.

Provides:
1. Supabase Postgres connection with fallback to local SQLite.
2. User authentication helpers (password hashing via bcrypt, JWT tokens).
3. Secure analysis persistence (crowd density metrics, spatial vectors).
4. SQL schema migrations for Supabase tables with Row Level Security (RLS).
5. Comprehensive admin query methods for users, analyses, and consent logs.
"""

import json
import logging
import os
import sqlite3
from typing import Any, Dict, List, Optional
from datetime import datetime, timezone

logger = logging.getLogger(__name__)

# Supabase SDK is optional at import time so tests run anywhere
try:
    from supabase import create_client, Client
    _HAS_SUPABASE = True
except ImportError:
    create_client = None  # type: ignore
    Client = None  # type: ignore
    _HAS_SUPABASE = False

# Fallback SQLite path
DB_PATH = os.environ.get(
    "VISIONLYTICS_DB_PATH",
    os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "visionlytics_fallback.db"),
)

SUPABASE_SCHEMA_SQL = """
-- Visionlytics Supabase PostgreSQL Schema with Row Level Security (RLS)

-- 1. Analysis History Table
CREATE TABLE IF NOT EXISTS public.analysis_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    source_type TEXT NOT NULL,
    people_count INTEGER NOT NULL,
    density_label TEXT NOT NULL,
    occupancy_ratio REAL NOT NULL,
    confidence REAL NOT NULL,
    features JSONB,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL
);

-- 2. Audit & Consent Logs
CREATE TABLE IF NOT EXISTS public.consent_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    consent_type TEXT NOT NULL,
    analytics_allowed BOOLEAN DEFAULT FALSE NOT NULL,
    ip_hash TEXT NOT NULL,
    user_agent TEXT
);

-- 3. App Users Table (Custom Profile & Credentials)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    hashed_password TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    is_verified BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. User Uploads Table (Uploaded Images, Metadata & Previews for Admin)
CREATE TABLE IF NOT EXISTS public.user_uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    username TEXT DEFAULT 'anonymous',
    email TEXT DEFAULT 'anonymous@visionlytics.io',
    filename TEXT NOT NULL,
    file_size_bytes INTEGER DEFAULT 0,
    content_type TEXT DEFAULT 'image/jpeg',
    thumbnail_base64 TEXT,
    people_count INTEGER DEFAULT 0,
    density_label TEXT DEFAULT 'LOW',
    confidence REAL DEFAULT 0.0
);

-- 5. Real-Time OTP Verification Codes
CREATE TABLE IF NOT EXISTS public.otp_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination TEXT NOT NULL,
    channel TEXT NOT NULL,
    code TEXT NOT NULL,
    expires_at BIGINT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Enable Row Level Security (RLS)
ALTER TABLE public.analysis_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consent_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.otp_codes ENABLE ROW LEVEL SECURITY;

-- 7. Policies
CREATE POLICY "Allow public read of anonymous analytics" ON public.analysis_history
    FOR SELECT USING (true);

CREATE POLICY "Allow service role or authenticated insert" ON public.analysis_history
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow service role or authenticated uploads" ON public.user_uploads
    FOR ALL USING (true);

CREATE POLICY "Allow service role OTP management" ON public.otp_codes
    FOR ALL USING (true);
"""


class SupabaseDatabaseClient:
    _instance = None

    def __new__(cls, *args, **kwargs):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._initialized = False
        return cls._instance

    def __init__(self, lazy: bool = True):
        if getattr(self, "_initialized", False):
            return
        self._initialized = True
        self.use_supabase = False
        self.client: Optional[Client] = None
        self.url = os.environ.get("SUPABASE_URL", "").strip()
        self.key = (
            os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "").strip()
            or os.environ.get("SUPABASE_KEY", "").strip()
        )
        if not lazy and os.environ.get("VISIONLYTICS_EAGER_DB", "0") == "1":
            self._init_connection()

    def _ensure_connection(self):
        if not self.use_supabase and self.client is None:
            self._init_connection()

    def _init_connection(self):
        if _HAS_SUPABASE and self.url and self.key:
            try:
                self.client = create_client(self.url, self.key)
                self.use_supabase = True
                logger.info("Connected to Supabase PostgreSQL database.")
                return
            except Exception as exc:
                logger.warning(f"Failed to connect to Supabase: {exc}. Falling back to SQLite.")
        
        self.use_supabase = False
        self._init_sqlite()

    def _init_sqlite(self):
        conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
        cursor = conn.cursor()
        cursor.execute("PRAGMA journal_mode=WAL;")
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS analysis_history (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
                source_type TEXT NOT NULL,
                people_count INTEGER NOT NULL,
                density_label TEXT NOT NULL,
                occupancy_ratio REAL NOT NULL,
                confidence REAL NOT NULL,
                features_json TEXT
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                phone TEXT,
                hashed_password TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'user',
                is_verified INTEGER DEFAULT 0,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS otp_codes (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                destination TEXT NOT NULL,
                channel TEXT NOT NULL,
                code TEXT NOT NULL,
                expires_at INTEGER NOT NULL,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS consent_logs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                consent_type TEXT NOT NULL,
                analytics_allowed INTEGER DEFAULT 0,
                ip_hash TEXT NOT NULL,
                user_agent TEXT,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS user_uploads (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT DEFAULT 'anonymous',
                email TEXT DEFAULT 'anonymous@visionlytics.io',
                filename TEXT NOT NULL,
                file_size_bytes INTEGER DEFAULT 0,
                content_type TEXT DEFAULT 'image/jpeg',
                thumbnail_base64 TEXT,
                people_count INTEGER DEFAULT 0,
                density_label TEXT DEFAULT 'LOW',
                confidence REAL DEFAULT 0.0,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.commit()
        conn.close()

    def save_analysis(
        self,
        source_type: str,
        features: Dict[str, Any],
        density_label: str,
        confidence: float,
        user_id: Optional[str] = None,
    ) -> bool:
        self._ensure_connection()
        features_subset = {
            "top_region_count": features.get("top_region_count", 0),
            "middle_region_count": features.get("middle_region_count", 0),
            "bottom_region_count": features.get("bottom_region_count", 0),
        }

        if self.use_supabase and self.client is not None:
            try:
                payload = {
                    "source_type": source_type,
                    "people_count": int(features.get("people_count", 0)),
                    "density_label": density_label,
                    "occupancy_ratio": float(features.get("occupancy_ratio", 0.0)),
                    "confidence": float(confidence),
                    "features": features_subset,
                }
                if user_id:
                    payload["user_id"] = user_id
                self.client.table("analysis_history").insert(payload).execute()
                return True
            except Exception as exc:
                logger.error(f"Failed saving to Supabase: {exc}")
                return False
        else:
            try:
                conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
                cursor = conn.cursor()
                cursor.execute("""
                    INSERT INTO analysis_history 
                    (source_type, people_count, density_label, occupancy_ratio, confidence, features_json)
                    VALUES (?, ?, ?, ?, ?, ?)
                """, (
                    source_type,
                    int(features.get("people_count", 0)),
                    density_label,
                    float(features.get("occupancy_ratio", 0.0)),
                    float(confidence),
                    json.dumps(features_subset)
                ))
                conn.commit()
                conn.close()
                return True
            except Exception as exc:
                logger.error(f"Failed saving to SQLite fallback: {exc}")
                return False

    def get_recent(self, limit: int = 100) -> List[Dict[str, Any]]:
        self._ensure_connection()
        limit = max(1, min(limit, 500))

        if self.use_supabase and self.client is not None:
            try:
                res = (
                    self.client.table("analysis_history")
                    .select("*")
                    .order("created_at", desc=True)
                    .limit(limit)
                    .execute()
                )
                return res.data or []
            except Exception as exc:
                logger.error(f"Failed fetching from Supabase: {exc}")
                return []
        else:
            if not os.path.exists(DB_PATH):
                return []
            conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
            conn.row_factory = sqlite3.Row
            cursor = conn.cursor()
            cursor.execute(
                "SELECT * FROM analysis_history ORDER BY timestamp DESC LIMIT ?",
                (limit,),
            )
            rows = cursor.fetchall()
            conn.close()

            results = []
            for row in rows:
                item = dict(row)
                if item.get("features_json"):
                    try:
                        item["features"] = json.loads(item["features_json"])
                    except Exception:
                        item["features"] = {}
                results.append(item)
            return results

    def get_all_users(self, limit: int = 200) -> List[Dict[str, Any]]:
        """Admin helper: fetch all users."""
        self._ensure_connection()
        if self.use_supabase and self.client is not None:
            try:
                res = self.client.table("users").select("id, username, email, phone, role, is_verified, created_at").limit(limit).execute()
                return res.data or []
            except Exception as exc:
                logger.error(f"Supabase fetch users failed: {exc}")

        conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        cursor.execute("SELECT id, username, email, phone, role, is_verified, created_at FROM users ORDER BY id DESC LIMIT ?", (limit,))
        rows = cursor.fetchall()
        conn.close()
        return [dict(r) for r in rows]

    def delete_user(self, user_id: int | str) -> bool:
        """Admin helper: delete user by id."""
        self._ensure_connection()
        if self.use_supabase and self.client is not None:
            try:
                self.client.table("users").delete().eq("id", user_id).execute()
                return True
            except Exception:
                pass

        conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
        cursor = conn.cursor()
        cursor.execute("DELETE FROM users WHERE id = ?", (user_id,))
        conn.commit()
        conn.close()
        return True

    def save_upload(
        self,
        filename: str,
        file_size_bytes: int = 0,
        content_type: str = "image/jpeg",
        thumbnail_base64: Optional[str] = None,
        username: str = "anonymous",
        email: str = "anonymous@visionlytics.io",
        people_count: int = 0,
        density_label: str = "LOW",
        confidence: float = 0.0,
    ) -> bool:
        """Store an uploaded image record with its metadata and preview thumbnail."""
        self._ensure_connection()
        if self.use_supabase and self.client is not None:
            try:
                self.client.table("user_uploads").insert({
                    "username": username,
                    "email": email,
                    "filename": filename,
                    "file_size_bytes": file_size_bytes,
                    "content_type": content_type,
                    "thumbnail_base64": thumbnail_base64,
                    "people_count": people_count,
                    "density_label": density_label,
                    "confidence": float(confidence),
                }).execute()
                return True
            except Exception as exc:
                logger.error(f"Supabase save_upload failed: {exc}")

        try:
            conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
            cursor = conn.cursor()
            cursor.execute("""
                INSERT INTO user_uploads (
                    username, email, filename, file_size_bytes, content_type,
                    thumbnail_base64, people_count, density_label, confidence
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                username, email, filename, file_size_bytes, content_type,
                thumbnail_base64, people_count, density_label, float(confidence)
            ))
            conn.commit()
            conn.close()
            return True
        except Exception as exc:
            logger.error(f"SQLite save_upload failed: {exc}")
            return False

