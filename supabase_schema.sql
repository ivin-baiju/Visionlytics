-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    hashed_password TEXT NOT NULL,
    role TEXT DEFAULT 'user' NOT NULL,
    is_verified BOOLEAN DEFAULT FALSE NOT NULL
);

-- 2. OTP Codes Table
CREATE TABLE IF NOT EXISTS public.otp_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    destination TEXT NOT NULL,
    channel TEXT NOT NULL,
    code TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    is_used BOOLEAN DEFAULT FALSE NOT NULL
);

-- 3. Analysis Records Table
CREATE TABLE IF NOT EXISTS public.analysis_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    source_type TEXT NOT NULL,
    people_count INTEGER NOT NULL,
    density_label TEXT NOT NULL,
    occupancy_ratio NUMERIC NOT NULL,
    confidence NUMERIC NOT NULL,
    features JSONB DEFAULT '{}'::jsonb
);

-- 4. User Uploads Table
CREATE TABLE IF NOT EXISTS public.user_uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    username TEXT DEFAULT 'Public User',
    email TEXT DEFAULT NULL,
    filename TEXT NOT NULL,
    file_size_bytes INTEGER DEFAULT 0,
    content_type TEXT DEFAULT 'image/jpeg',
    thumbnail_base64 TEXT,
    people_count INTEGER DEFAULT 0,
    density_label TEXT DEFAULT 'LOW',
    confidence NUMERIC DEFAULT 0.0
);

-- 5. Consent Logs Table
CREATE TABLE IF NOT EXISTS public.consent_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    consent_type TEXT NOT NULL,
    analytics_allowed BOOLEAN DEFAULT TRUE NOT NULL,
    ip_hash TEXT NOT NULL,
    user_agent TEXT
);

